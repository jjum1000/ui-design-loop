"""A0 준비: ROADMAP.md 의 코드 블록과 절을 ui-audit/ 파일로 옮기고 상태 파일을 만든다.
기획 문서(ROADMAP.md)를 읽는 것은 A0 만 한다. 이후 세션은 이 스크립트가 만든 파일만 쓴다.

사용:
  python scripts/a0_setup.py                 전체 A0 (manifest.json 이 있으면 거부)
  python scripts/a0_setup.py --force-reset   사용자가 명시했을 때만: 진행 상태를 버리고 다시 만든다
  python scripts/a0_setup.py --docs-only     문서를 고친 뒤: agents/(A1~A6·L1·H1~H3·F)·spec/catalog.md·schemas/·handoff/START.md 만 다시 만들고
                                             scripts/·data/·상태 파일은 건드리지 않는다. 끝에 자체 테스트와 기존 data 검증.
  python scripts/a0_setup.py --check         모든 스크립트 자체 테스트 + 기존 data 검증만
  python scripts/a0_setup.py --selftest      ROADMAP 추출 검사
spec/steps.json·spec/batch-plan.json 은 스크립트 규칙·실제 폴더 대응이라 없을 때만 경고하고 덮어쓰지 않는다.
"""
import argparse
import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as C  # noqa: E402

RUN_FROM = "> Working folder is ui-audit/. Run every command from this folder. This file was generated by A0 (scripts/a0_setup.py) from ROADMAP.md.\n"
DOC_TARGETS = (["handoff/START.md", "agents/L1.md", "agents/_common.md"] + ["agents/A%d.md" % i for i in range(1, 7)]
               + ["agents/%s.md" % g for g in ("H1", "H2", "H3", "F")])
SELFTESTS = ["validate.py", "parse_prefab.py", "classify_rules.py", "group.py", "cluster_values.py", "questions.py",
             "batch.py", "build_catalog.py", "a0_setup.py", "state.py", "record_decision.py",
             "template_scope.py", "scene_enum.py", "usage_graph.py", "code_usage.py", "templates.py", "thumbs.py", "layout_map.py",
             "ds_index.py", "ds_skeletons.py", "ds_roles.py", "ds_colors.py", "ds_screens.py", "ds_publish.py"]


def selftests():
    """도구 자체 테스트 + project.json project_producers.selftests(프로젝트 전용 생산자 — 파일이 있을 때만)."""
    extra = ((C.project() or {}).get("project_producers") or {}).get("selftests", [])
    return SELFTESTS + [s for s in extra if os.path.exists(os.path.join(C.SCRIPTS, s))]


def roadmap():
    path = C.p("ROADMAP.md")
    if not os.path.exists(path):
        raise SystemExit("ROADMAP.md 없음 — A0 는 기획 문서가 있는 세션에서만 실행")
    with open(path, encoding="utf-8") as f:
        return f.read()


def blocks_by_target(text):
    """'### 제목 (`경로`)' 바로 뒤의 첫 코드 블록 → {경로: 본문}"""
    out = {}
    for m in re.finditer(r"^###[^\n]*\(`([^`]+)`\)[^\n]*\n(.*?)^```[^\n]*\n(.*?)^```", text, re.S | re.M):
        out[m.group(1)] = m.group(3)
    return out


def section(text, title):
    m = re.search(r"^## %s\n(.*?)(?=^## |\Z)" % re.escape(title), text, re.S | re.M)
    if not m:
        raise SystemExit("ROADMAP 에 '## %s' 절이 없음" % title)
    return m.group(1).strip() + "\n"


def write(rel, content):
    path = C.p(rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    return rel


def step_appendix(step):
    spec = C.load_json(C.p("spec", "steps.json"))
    if not spec or step not in spec:
        return ""
    s = spec[step]
    lines = ["", "---", "", "## 명령 참고 (A0 이 spec/steps.json 에서 덧붙임 — 위 지시가 우선)", "",
             "- 완료 조건 검사: " + ", ".join("%s(%s)" % (c, spec["checkDescriptions"].get(c, "")) for c in s["checks"]),
             "- 산출: " + ", ".join(s["outputs"]), ""]
    lines += ["    " + c.replace("{batch}", "<batch>") for c in s["commands"]]
    lines += ["", "각 스크립트 사용법: python scripts/<이름>.py -h", ""]
    return "\n".join(lines)


def write_docs(text):
    made = []
    blocks = blocks_by_target(text)
    need = DOC_TARGETS
    miss = [x for x in need if x not in blocks]
    if miss:
        raise SystemExit("ROADMAP 에서 코드 블록을 찾지 못함: %s" % miss)
    for rel in need:
        body = blocks[rel]
        if rel.startswith("agents/A"):
            body = RUN_FROM + "\n" + body + step_appendix(os.path.basename(rel)[:-3])
        elif body.startswith(RUN_FROM.split(".")[0]):  # 블록이 같은 안내를 이미 가지면 다시 붙이지 않는다
            pass
        else:
            body = RUN_FROM + "\n" + body
        made.append(write(rel, body))
    cat = section(text, "HTML catalog layout")
    made.append(write("spec/catalog.md", "# HTML 카탈로그 구성 (spec)\n\n" + RUN_FROM + "\n" + cat +
                      "\n## 구현 메모\n\n- 생성: python scripts/build_catalog.py --page <페이지> → validate.py --rename catalog\n"
                      "- 검사: python scripts/build_catalog.py --check (깨진 링크·이미지 0개)\n"
                      "- 상태 표시: decisions.json 의 마지막 결정(표준·폐기·예외)이 그룹·토큰의 미검토·후보보다 우선\n"))
    import schema_defs
    for name, sch in schema_defs.build().items():
        full = {"$schema": "https://json-schema.org/draft/2020-12/schema", "title": name}
        full.update(sch)
        made.append(write("schemas/%s.json" % name, json.dumps(full, ensure_ascii=False, indent=1) + "\n"))
    for rel in ("spec/steps.json", "spec/batch-plan.json", "project.json"):
        if not os.path.exists(C.p(rel)):
            print("경고: %s 없음 — 스크립트 규칙·실제 폴더 대응 파일이라 자동 생성하지 않음" % rel)
    return made


def run_checks():
    ok = True
    for s in selftests():
        r = subprocess.run([sys.executable, os.path.join(C.SCRIPTS, s), "--selftest"], capture_output=True,
                           text=True, encoding="utf-8", env=dict(os.environ, PYTHONIOENCODING="utf-8"))
        last = ((r.stdout or "") + (r.stderr or "")).strip().splitlines()
        print("%s %s: %s" % ("ok  " if r.returncode == 0 else "FAIL", s, last[-1] if last else ""))
        ok &= r.returncode == 0
    import validate
    files = [f for d in ("data", "batches") for f in validate.expand([C.p(d)]) if not f.endswith(".tmp")]
    files += [C.p(x) for x in ("manifest.json", "project.json", "decisions.json", "questions.json") if os.path.exists(C.p(x))]
    bad = 0
    for f in files:
        if "/.work/" in f.replace("\\", "/") or "/.bak/" in f.replace("\\", "/"):
            continue
        errs = validate.validate_file(f)
        if errs:
            bad += 1
            print("data 불일치: %s — %s" % (os.path.relpath(f, C.ROOT), errs[0]))
    print("기존 data·상태 파일 검증: %d개 중 불일치 %d" % (len(files), bad))
    return ok and bad == 0


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--docs-only", action="store_true")
    ap.add_argument("--force-reset", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    if a.check:
        return 0 if run_checks() else 1
    if a.docs_only:
        made = write_docs(roadmap())
        print("다시 만든 파일 %d개 (agents/ — H1·H2·H3·F 포함, spec/catalog.md, schemas/, handoff/START.md)" % len(made))
        if not run_checks():
            print("멈춤: 자체 테스트 또는 기존 data 검증이 새 스키마와 어긋남 — 위 목록 확인")
            return 1
        return 0
    if os.path.exists(C.p("manifest.json")) and not a.force_reset:
        print("거부: manifest.json 이 이미 있음 — 진행 상태를 잃으므로 실행하지 않음 (--force-reset 을 사용자가 명시할 때만)")
        return 1
    made = write_docs(roadmap())
    for d in ("batches", "input/screenshots", "data", "previews", "catalog", "reports", "cache"):
        os.makedirs(C.p(d), exist_ok=True)
    made.append(write("handoff/log.md", ""))
    for f in ("decisions.json", "questions.json"):
        made.append(write(f, "[]\n"))
    if a.force_reset and os.path.exists(C.p("manifest.json")):
        os.remove(C.p("manifest.json"))
    r = subprocess.run([sys.executable, os.path.join(C.SCRIPTS, "state.py"), "init"] + (["--force-reset"] if a.force_reset else []),
                       capture_output=True, text=True, encoding="utf-8", env=dict(os.environ, PYTHONIOENCODING="utf-8"))
    print((r.stdout or "") + (r.stderr or ""), end="")
    if r.returncode:
        return 1
    print("A0 파일 %d개 + manifest.json. 다음: python scripts/a0_setup.py --check, python scripts/state.py render" % len(made))
    return 0


def selftest():
    text = roadmap()
    b = blocks_by_target(text)
    for rel in DOC_TARGETS:
        assert rel in b and len(b[rel]) > 100, "블록 추출 실패: %s" % rel
    assert "session manager (L0)" in b["handoff/START.md"]
    # START.md = RUN_FROM + block: write_docs prepends RUN_FROM because the block carries no '>' header of its own
    assert RUN_FROM.startswith("> Working folder is ui-audit/") and not b["handoff/START.md"].startswith(">"), \
        "START.md must begin with RUN_FROM ('> Working folder is ui-audit/'); the block itself must not add a '>' header"
    assert "autonomous mode" in b["handoff/START.md"] and "agents/F.md" in b["handoff/START.md"]
    for g in ("H1", "H2", "H3", "F"):
        assert b["agents/%s.md" % g].startswith("Input:"), "%s block must start with 'Input:'" % g
    assert "--by agent" in b["agents/H2.md"] and "--by agent" in b["agents/H3.md"]
    assert b["agents/A1.md"].startswith("Input:"), "A1 block must start with 'Input:'"
    cat = section(text, "HTML catalog layout")
    assert "refactor-map.html" in cat and "index.html" in cat
    import schema_defs
    assert len(schema_defs.build()) == 22
    print("a0_setup.py selftest ok")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
